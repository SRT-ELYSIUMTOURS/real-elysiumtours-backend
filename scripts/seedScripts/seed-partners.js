// ── Minimal inline schemas (seed-only) ────────────────────────────────────────

const PackageItemSchema = {
	id: String, title: String, price: String,
	description: String, features: [String], highlighted: Boolean,
};

const DestinationSchema = new mongoose.Schema(
	{ name: String, country: String, region: String },
	{ collection: "destinations" }
);

const AttractionSchema = new mongoose.Schema(
	{
		name: String, organizationId: mongoose.Schema.Types.ObjectId,
		destinationId: { type: mongoose.Schema.Types.ObjectId, ref: "Destination", required: true },
		category: String, entryFee: Number, description: String,
		images: [String], coverImage: String, rating: Number, reviewCount: Number,
		duration: String, suitableFor: [String], isActive: Boolean,
		operatingHours: { open: String, close: String, weekdays: String },
		contactInfo: { phone: String, email: String },
	},
	{ timestamps: true, collection: "attractions" }
);

const HotelPartnerSchema = new mongoose.Schema(
	{
		name: String, organizationId: mongoose.Schema.Types.ObjectId,
		destinationId: { type: mongoose.Schema.Types.ObjectId, ref: "Destination", required: true },
		tier: String, commissionRate: Number,
		contactInfo: { contactPerson: String, phone: String, email: String, address: String },
		amenities: [String], images: [String], coverImage: String,
		starRating: Number, rating: Number, reviewCount: Number,
		shortDescription: String, priceRange: String,
		rateData: { standardRate: Number },
		availabilityStatus: String, inventoryModel: String,
		contractStatus: String, isActive: Boolean,
		packages: [PackageItemSchema],
	},
	{ timestamps: true, collection: "hotelpartners" }
);

const DiningPartnerSchema = new mongoose.Schema(
	{
		name: String, organizationId: mongoose.Schema.Types.ObjectId,
		destinationId: { type: mongoose.Schema.Types.ObjectId, ref: "Destination", required: true },
		cuisineType: String, tier: String, commissionRate: Number,
		contactInfo: { phone: String, email: String, address: String },
		images: [String], coverImage: String, rating: Number, reviewCount: Number,
		openingHours: String, priceRange: String, isActive: Boolean,
	},
	{ timestamps: true, collection: "diningpartners" }
);

const TransportProviderSchema = new mongoose.Schema(
	{
		companyName: String, contactPerson: String, phone: String, email: String,
		description: String, coverImage: String, images: [String],
		serviceAreas: [String], vehicleTypes: [String],
		baseRatePerKm: Number, rating: Number, reviewCount: Number,
		commissionRate: Number, isActive: Boolean,
		packages: [PackageItemSchema],
	},
	{ timestamps: true, collection: "transportproviders" }
);

const TourGuideSchema = new mongoose.Schema(
	{
		name: String, email: String, phone: String,
		specialities: [String], languages: [String],
		bio: String, avatar: String, galleryImages: [String], country: String,
		rating: Number, reviewCount: Number, isActive: Boolean,
	},
	{ timestamps: true, collection: "tourguides" }
);

const PhotographerPartnerSchema = new mongoose.Schema(
	{
		name: String, bio: String, specialties: [String],
		portfolio: [String], coverImage: String, avatar: String,
		languages: [String], baseRatePerDay: Number,
		rating: Number, reviewCount: Number, isActive: Boolean,
		contactInfo: { phone: String, email: String, website: String },
	},
	{ timestamps: true, collection: "photographerpartners" }
);

const ServicePartnerSchema = new mongoose.Schema(
	{
		name: String, serviceType: String, description: String,
		coverImage: String, images: [String], priceRange: String,
		rating: Number, reviewCount: Number, isActive: Boolean,
		contactInfo: { phone: String, email: String, website: String },
	},
	{ timestamps: true, collection: "servicepartners" }
);

// ── Models ────────────────────────────────────────────────────────────────────
const Destination        = mongoose.model("Destination",        DestinationSchema);
const Attraction         = mongoose.model("Attraction",         AttractionSchema);
const HotelPartner       = mongoose.model("HotelPartner",       HotelPartnerSchema);
const DiningPartner      = mongoose.model("DiningPartner",      DiningPartnerSchema);
const TransportProvider  = mongoose.model("TransportProvider",  TransportProviderSchema);
const TourGuide          = mongoose.model("TourGuide",          TourGuideSchema);
const PhotographerPartner = mongoose.model("PhotographerPartner", PhotographerPartnerSchema);
const ServicePartner     = mongoose.model("ServicePartner",     ServicePartnerSchema);

